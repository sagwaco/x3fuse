/// sRGB white (D65) as xy → XYZ, exactly as spektrafilm derives it.
pub fn srgb_white() -> [f64; 3] {
    xy_to_xyz(0.3127, 0.329)
}

pub fn xy_to_xyz(x: f64, y: f64) -> [f64; 3] {
    if y <= 0.0 {
        return [0.0, 0.0, 0.0];
    }
    [x / y, 1.0, (1.0 - x - y) / y]
}

/// CIE xy → spektrafilm triangular/quad LUT coordinates (Python `_tri2quad`).
pub fn xy_to_tc(x: f64, y: f64) -> (f64, f64) {
    let tx = (1.0 - x) * (1.0 - x);
    let ty = y / (1.0 - x).max(1e-10);
    (tx.clamp(0.0, 1.0), ty.clamp(0.0, 1.0))
}

/// Inverse of [`xy_to_tc`] (Python `_quad2tri`); the shared `sqrt` matters.
pub fn tc_to_xy(tx: f64, ty: f64) -> (f64, f64) {
    let sq = tx.max(0.0).sqrt();
    (1.0 - sq, ty * sq)
}

/// spektrafilm's illuminant lookup: named standard illuminants, D55 otherwise.
/// The bundled profiles only ever name D50, D55, TH-KG3 or "T"; the last two
/// fall through, which is how the tungsten-balanced stocks resolve to D55.
pub fn reference_illuminant(name: &str) -> (&'static [f64], [f64; 3]) {
    match name {
        "D50" => (&ILLUMINANT_D50_F64, D50_WHITE),
        _ => (&ILLUMINANT_D55_F64, D55_WHITE),
    }
}

/// Integrate an SPD against the CIE 1931 2° observer and normalise to Y = 1
/// through the xy round-trip spektrafilm uses.
pub fn illuminant_white(illuminant: &[f64]) -> [f64; 3] {
    let mut xyz = [0.0f64; 3];
    for i in 0..N_WL.min(illuminant.len()) {
        xyz[0] += illuminant[i] * CMF_X_F64[i];
        xyz[1] += illuminant[i] * CMF_Y_F64[i];
        xyz[2] += illuminant[i] * CMF_Z_F64[i];
    }
    let sum = xyz[0] + xyz[1] + xyz[2];
    if sum <= 0.0 || xyz[1] <= 0.0 {
        return [1.0, 1.0, 1.0];
    }
    xy_to_xyz(xyz[0] / sum, xyz[1] / sum)
}


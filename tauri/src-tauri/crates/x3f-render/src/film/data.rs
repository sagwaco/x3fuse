/// von Kries adaptation `inv · diag(dst/src) · fwd`.
fn von_kries(
    src: [f64; 3],
    dst: [f64; 3],
    fwd: &[[f64; 3]; 3],
    inv: &[[f64; 3]; 3],
) -> [[f64; 3]; 3] {
    let cone = |w: [f64; 3]| -> [f64; 3] {
        std::array::from_fn(|i| fwd[i][0] * w[0] + fwd[i][1] * w[1] + fwd[i][2] * w[2])
    };
    let s = cone(src);
    let d = cone(dst);
    let gain: [f64; 3] = std::array::from_fn(|i| d[i] / s[i]);
    let mut out = [[0.0f64; 3]; 3];
    for i in 0..3 {
        for j in 0..3 {
            out[i][j] = inv[i][0] * gain[0] * fwd[0][j]
                + inv[i][1] * gain[1] * fwd[1][j]
                + inv[i][2] * gain[2] * fwd[2][j];
        }
    }
    out
}
pub fn cat02(src: [f64; 3], dst: [f64; 3]) -> [[f64; 3]; 3] {
    von_kries(src, dst, &CAT02_FWD, &CAT02_INV)
}
pub fn cat16(src: [f64; 3], dst: [f64; 3]) -> [[f64; 3]; 3] {
    von_kries(src, dst, &CAT16_FWD, &CAT16_INV)
}
pub fn mat_mul(a: &[[f64; 3]; 3], b: &[[f64; 3]; 3]) -> [[f64; 3]; 3] {
    let mut out = [[0.0f64; 3]; 3];
    for i in 0..3 {
        for j in 0..3 {
            out[i][j] = a[i][0] * b[0][j] + a[i][1] * b[1][j] + a[i][2] * b[2][j];
        }
    }
    out
}
